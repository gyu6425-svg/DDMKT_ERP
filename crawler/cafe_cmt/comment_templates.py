def classify_business(text):
    """제목이나 댓글 문구를 보고 업종 키워드('누수탐지'/'보안')를 고른다.
    아무 것도 안 걸리면 None(호출부가 기본값/스킵을 정한다)."""
    t = (text or '')
    for kw, terms in BUSINESS_TERMS:
        if any(term in t for term in terms):
            return kw
