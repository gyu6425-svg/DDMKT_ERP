function pick(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
}

// 본문 순수 글자수 — 사진 마커 없는 양식이라 줄바꿈만 제거(파이썬 _blen 과 동일).
export function bodyLen(body) {
    return String(body ?? '').replace(/\n/g, '').length;
}

